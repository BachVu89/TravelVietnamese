#!/usr/bin/env python3
"""Create an isolated HDRP desktop snapshot; never overwrite an existing project.
Runtime/art are copied from the mobile source; HDRP uses its own Editor bootstrap.
"""
import argparse
import hashlib
import json
from pathlib import Path
import shutil
import sys

ROOT=Path(__file__).resolve().parents[1]
SOURCE=ROOT/'unity/TravelVietnamese'

def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--output',type=Path,default=ROOT/'unity/TravelVietnamese-HDRP')
    p.add_argument('--verify',action='store_true',help='Compare shared Runtime/art source without writing')
    a=p.parse_args();target=a.output.resolve()
    folders=['Assets/TravelVietnamese/Runtime','Assets/TravelVietnamese/Art/Original']
    if a.verify:
        for folder in folders:
            for original in (SOURCE/folder).rglob('*'):
                if not original.is_file() or original.suffix=='.meta':continue
                other=target/original.relative_to(SOURCE)
                if not other.is_file() or hashlib.sha256(original.read_bytes()).digest()!=hashlib.sha256(other.read_bytes()).digest():
                    p.exit(1,f'HDRP snapshot differs: {other}\n')
        print('SHARED SOURCE MATCH: Runtime/FBX snapshots only; no Unity compile/render.')
        return 0
    if target.exists():p.exit(2,'Refusing to overwrite an existing project. Generate elsewhere and review a diff.\n')
    for folder in folders:shutil.copytree(SOURCE/folder,target/folder)
    shutil.copytree(SOURCE/'ProjectSettings',target/'ProjectSettings')
    manifest=json.loads((SOURCE/'Packages/manifest.json').read_text())
    manifest['dependencies'].pop('com.unity.render-pipelines.universal')
    manifest['dependencies']['com.unity.render-pipelines.high-definition']='17.0.3'
    (target/'Packages').mkdir();(target/'Packages/manifest.json').write_text(json.dumps(manifest,indent=2)+'\n')
    editor=(SOURCE/'Assets/TravelVietnamese/Editor/PassProjectSetup.cs').read_text()
    editor=editor.replace('using UnityEngine.Rendering.Universal;','using UnityEngine.Rendering.HighDefinition;')
    editor=editor.replace('PassProjectSetup','DesktopPassSetup').replace('Universal Render Pipeline/Lit','HDRP/Lit')
    editor=editor.replace('resolved URP packages','resolved HDRP packages').replace('Resolve URP before','Resolve HDRP before')
    start=editor.index('        static void MobilePipeline()')
    end=editor.index('        [MenuItem',start)
    setup='''        static void DesktopPipeline()
        {
            if (!(GraphicsSettings.defaultRenderPipeline is HDRenderPipelineAsset))
                throw new InvalidOperationException("Configure HDRP using Window > Rendering > HDRP Wizard first; this desktop project is not a mobile build.");
            UnityEngine.Object[] settings=AssetDatabase.LoadAllAssetsAtPath("ProjectSettings/ProjectSettings.asset");
            if(settings.Length>0)
            {
                SerializedObject serialized=new SerializedObject(settings[0]);
                SerializedProperty input=serialized.FindProperty("activeInputHandler");
                if(input!=null){input.intValue=0;serialized.ApplyModifiedPropertiesWithoutUndo();}
            }
        }
'''
    editor=editor[:start]+setup+editor[end:]
    editor=editor.replace('MobilePipeline();','DesktopPipeline();').replace('Create Mobile Pass','Create Desktop Reference Pass').replace('CreateMobilePass','CreateDesktopPass')
    editor=editor.replace('if(twoSided){material.SetFloat("_Cull",0);material.doubleSidedGI=true;}', 'if(twoSided){material.SetFloat("_CullMode",0);material.SetFloat("_DoubleSidedEnable",1);material.EnableKeyword("_DOUBLESIDED_ON");material.doubleSidedGI=true;}')
    # Desktop atmosphere is configured in HDRP Volumes in the Editor, not legacy fog.
    editor=editor.replace('            RenderSettings.fog=true;', '            // Configure HDRP Fog/Volumetric Clouds in a global Volume after creation.\n            RenderSettings.fog=true;')
    start=editor.index('        public static void BuildAndroid()')
    editor=editor[:start]+'    }\n}\n'
    path=target/'Assets/TravelVietnamese/Editor';path.mkdir(parents=True)
    (path/'DesktopPassSetup.cs').write_text(editor)
    (target/'README.md').write_text('''# Unity HDRP desktop reference source

Generated by `scripts/create-unity-hdrp-reference.py` from the mobile Runtime/FBX source.
This is a desktop-only snapshot, not an Android/iOS project or a rendered reference.

Open in the pinned Unity 6 Editor, resolve HDRP, run **Window > Rendering > HDRP Wizard**
to configure valid HDRP assets/global settings, then **TravelVietnamese > Create Desktop Reference Pass**.
Configure a global Volume for HDRP sky/fog/clouds and review lighting/materials. Legacy runtime
RenderSettings fog does not implement HDRP volumetric fog. No scene or pipeline asset exists yet.
The script preserves existing scenes/materials. No Android build entrypoint is provided.

Do not edit duplicated Runtime/FBX files independently: update the mobile source, generate a new
snapshot at a temporary `--output` path, review the diff, and retain any desktop-specific artist work.
`python3 scripts/create-unity-hdrp-reference.py --verify` checks shared-source parity only.
Unity compile, license activation, package resolution, render and desktop performance remain unverified.
''')
    print('Created HDRP desktop source snapshot:',target)
    return 0

if __name__=='__main__':sys.exit(main())
